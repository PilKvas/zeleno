/// Состояние системного разрешения на уведомления.
///
/// Приложение не хранит собственный флаг «хочу уведомления»: единственный
/// источник правды — ОС. Поэтому тумблер в профиле не выключается изнутри,
/// а ведёт в системные настройки (см. [PushPermissionStatus.denied]).
enum PushPermissionStatus {
  /// Системный диалог ещё не показывали — его можно вызвать из приложения.
  notDetermined,

  /// Разрешение выдано, пуши доходят.
  granted,

  /// Пользователь отказал. Вернуть разрешение можно только в настройках ОС:
  /// системный диалог одноразовый и повторно не покажется.
  denied;

  bool get isGranted => this == PushPermissionStatus.granted;

  bool get isNotDetermined => this == PushPermissionStatus.notDetermined;
}
